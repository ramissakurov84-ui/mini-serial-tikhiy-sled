def build_project():
    OUT.mkdir(exist_ok=True)
    for episode in SERIES["episodes"]:
        ep_dir = OUT / f"episode_{episode['id']:02d}_{episode['title'].lower().replace(' ', '_')}"
        ep_dir.mkdir(exist_ok=True)
        for idx, scene in enumerate(episode["scenes"], start=1):
            scene_file = ep_dir / f"scene_{idx:02d}_{scene['title'].lower().replace(' ', '_')}.json"
            payload = {
                "episode_id": episode["id"],
                "episode_title": episode["title"],
                "scene_id": idx,
                "scene_title": scene["title"],
                "prompt": scene["prompt"],
                "voiceover": scene["voiceover"],
                "notes": scene["notes"],
                "video_style": "cinematic noir, realistic, dark urban thriller",
            }
            scene_file.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")

    meta = {"series": SERIES}
    (OUT / "series_manifest.json").write_text(json.dumps(meta, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Создан каталог {OUT} с {len(SERIES['episodes'])} эпизодами.")


if __name__ == "__main__":
    build_project()
